"""Select a stacked classifier over existing hand-only OOF heads.

All columns come from persisted grouped OOF predictions.  No robot manifest
or robot labels are read by this selector.
"""
from pathlib import Path
import json
import warnings
import numpy as np
import pandas as pd
from sklearn.linear_model import LogisticRegression
from sklearn.metrics import f1_score
from sklearn.model_selection import StratifiedGroupKFold
from sklearn.pipeline import make_pipeline
from sklearn.preprocessing import StandardScaler

ROOT = Path('/home/ttung05/Desktop/tree_base/tree_structures')
INP = Path('outputs/audio_feature_benchmarks/segment_hier_contact_rescue_group_selection')
OUT = Path('outputs/audio_feature_benchmarks/all_head_stack_group_selection')

def make_z(a):
    cols=[]
    for x in a:
        x=np.asarray(x,dtype=np.float64)
        if x.ndim==1: x=x[:,None]
        cols.extend([x,np.log(np.clip(x,1e-6,1))])
    return np.hstack(cols).astype(np.float32)

def macro(y,p):
    vals=[]
    for c in range(4):
        tp=((p==c)&(y==c)).sum();fp=((p==c)&(y!=c)).sum();fn=((p!=c)&(y==c)).sum()
        vals.append(2*tp/(2*tp+fp+fn) if 2*tp+fp+fn else 0.)
    return float(np.mean(vals))

def main():
    warnings.filterwarnings("ignore")
    OUT.mkdir(parents=True,exist_ok=True)
    q=np.load(INP/'hand_oof_arrays.npz',allow_pickle=True)
    y=q['sy'].astype(np.int64); groups=q['ss'].astype(str)
    # The arrays are generated by grouped hand OOF in the source selector.
    heads=[q[k] for k in ['seg_pc','seg_audio_mat','seg_audio4','img_contact_clip','img_contact_cat','img_mat_clip','img_mat_eff','img_mat_cat','img4_clip','trunk_oof']]
    z=make_z(heads)
    folds=list(StratifiedGroupKFold(5,shuffle=True,random_state=42).split(np.arange(len(y)),y,groups))
    rows=[]
    for C in (0.01,0.03,0.1):
        for tw in (1.0,1.2,1.5):
            for gw in (1.0,1.2,1.5):
                cw={0:1.,1:1.,2:tw,3:gw}; scores=[]
                for tr,va in folds:
                    m=make_pipeline(StandardScaler(),LogisticRegression(C=C,max_iter=3000,class_weight=cw,multi_class='multinomial',random_state=42))
                    m.fit(z[tr],y[tr]); scores.append(macro(y[va],m.predict(z[va])))
                rows.append({'C':C,'trunk_class_weight':tw,'twig_class_weight':gw,'mean_cv_macro_f1':float(np.mean(scores)),'worst_cv_macro_f1':float(np.min(scores))})
    board=pd.DataFrame(rows).sort_values(['worst_cv_macro_f1','mean_cv_macro_f1'],ascending=False).reset_index(drop=True)
    board.to_csv(OUT/'hand_head_stack_leaderboard.csv',index=False)
    best=board.iloc[0].to_dict()
    np.save(OUT/'hand_stack_features.npy',z); np.save(OUT/'hand_stack_y.npy',y)
    lock={'protocol':'all_existing_heads_grouped_hand_oof_stack','selection_data':'hand/default only','group_column':'specimen_group','candidate':best,'test_loaded':False}
    (OUT/'selection_lock.json').write_text(json.dumps(lock,indent=2,default=float))
    print(json.dumps(lock,indent=2,default=float)); print(board.head(12).to_string(index=False))

if __name__=='__main__': main()
